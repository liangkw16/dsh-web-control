import {test,expect,nativeInput} from './native-ui-fixtures.ts'
import {readFile} from 'node:fs/promises'
import {documents} from './native-current-documents.ts'
for(const width of [360,390,1280])test(`original current-file preview and download at ${width} CSS pixels`,async({nativePage,nativeFixture,browserName})=>{
  await nativeFixture.documents({'fixture.png':documents['fixture.png']},true)
  await nativeFixture.documents({'fixture.txt':documents['fixture.txt'],'fixture.md':Buffer.from('# Native mobile Markdown\n\n![Inline image](fixture.png)')})
  await nativePage.getByRole('treeitem',{name:/Native UI verification/}).click()
  await nativeInput(nativePage).fill('Keep this preview draft')
  await nativePage.setViewportSize({width,height:800})
  await nativePage.getByRole('button',{name:'在侧边栏预览 fixture.txt',exact:true}).click()
  const panel=nativePage.locator('[data-textpreview-state]')
  await expect(panel.locator('[data-textpreview-body]')).toContainText('原版文件预览')
  const bounds=await panel.boundingBox();expect(bounds!.x).toBeGreaterThanOrEqual(0);expect(bounds!.x+bounds!.width).toBeLessThanOrEqual(width)
  const pending=nativePage.waitForEvent('download');await panel.getByRole('button',{name:'下载文件',exact:true}).click()
  const download=await pending;expect(download.suggestedFilename()).toBe('fixture.txt');expect(await readFile((await download.path())!)).toEqual(documents['fixture.txt'])
  // WebKit's screenshotter injects "body {}" to synchronize animations. Keep its
  // screenshot after product CSP collection in the fixture's existing teardown.
  if(browserName==='chromium')await nativePage.screenshot({path:`${nativeFixture.dir}/current-preview-${width}.png`})
  await nativePage.getByRole('tab',{name:'fixture.txt 关闭',exact:true}).getByRole('button',{name:'关闭',exact:true}).click()
  await expect(nativeInput(nativePage)).toHaveText('Keep this preview draft')
  await nativePage.getByRole('button',{name:'在侧边栏预览 fixture.md',exact:true}).click()
  await expect.poll(()=>panel.getByRole('img',{name:'Inline image',exact:true}).evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBe(16)
  await nativePage.getByRole('tab',{name:'fixture.md 关闭',exact:true}).getByRole('button',{name:'关闭',exact:true}).click()
  await expect(nativeInput(nativePage)).toHaveText('Keep this preview draft')
  expect(await nativeFixture.counts(nativeFixture.sessionId)).toEqual({starts:0,stops:0,prompts:0})
})
